<h2>What direct registration is</h2>
<p>
	<strong>Direct registration</strong> is how receiving staff create a testing request
	when the customer did not start from the online portal — walk-in, courier drop-off, or phone-arranged work.
	You start from <strong>Sample Workflow → Samples Receiving</strong>, usually on
	<strong>Ready for Reception</strong>.
</p>

