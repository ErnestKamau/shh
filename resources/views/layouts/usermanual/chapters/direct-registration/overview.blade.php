<h2>Open the form</h2>
<p>
	Press <strong>Direct Registration</strong> (header button or Actions). Choose a published
	testing form (TRF), fill it, then accept samples without leaving the window.
</p>

@include('layouts.usermanual.partials.figure', [
	'src' => '/images/usermanual/direct-registration/overview.png',
	'caption' => 'Direct Registration — choose a published testing form (TRF) to open.',
