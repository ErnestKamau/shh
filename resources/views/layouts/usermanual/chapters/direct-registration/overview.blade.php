<h2>How it differs from a portal request</h2>
<ul>
	<li><strong>Portal</strong> — customer fills the form outside; you receive it already drafted.</li>
	<li><strong>Direct registration</strong> — you choose the right form and fill it in for them inside the lab system.</li>
</ul>

<div class="um-tip">
	<span class="um-tip__icon"><i class="mdi mdi-account-plus-outline"></i></span>
	<p>Use direct registration when samples are arriving and there is no usable online draft yet.</p>
</div>
