<h2>Asset Depreciation (sidebar)</h2>
<p>
	If you have permission, the sidebar shows <strong>Asset Depreciation</strong> with three children:
</p>
<ol>
	<li><strong>Depreciation List</strong> — register of assets with depreciation enabled and current book-value style information.</li>
	<li><strong>Depreciation Methods</strong> — define or review calculation methods used on the create/edit wizard step 5.</li>
	<li><strong>Reports</strong> (under depreciation) — depreciation-specific reports.</li>
</ol>

<h3>Enabling depreciation on an asset</h3>
<ol>
	<li>Edit the equipment → step <strong>Depreciation</strong>.</li>
	<li>Turn on <strong>Enable Depreciation</strong>.</li>
	<li>Set <strong>Currency *</strong>, optional <strong>Freight / Installation Cost</strong>, review <strong>Capitalized Amount</strong>.</li>
	<li>Choose <strong>Method *</strong> and <strong>Depreciation Frequencies *</strong>, plus any method-specific fields shown.</li>
	<li><strong>Save</strong>. Review later on the profile tab <strong>Asset Depreciation</strong>.</li>
</ol>

<div class="um-tip">
	<span class="um-tip__icon"><i class="mdi mdi-lightbulb-on-outline"></i></span>
	<p>
		Periodic depreciation processing may run on a schedule in the background.
		Use Depreciation List and depreciation Reports to review outcomes; fix method or basis on the asset if figures look wrong.
	</p>
</div>

<h2>Equipment Reports (sidebar)</h2>
<p>
	Open <strong>Equipment → Reports</strong> (Equipment Reports home).
	Generate the operational reports your organisation uses for the equipment register
	(maintenance/calibration oriented outputs and related selections on that screen).
</p>

<h2>Other exports you will meet elsewhere</h2>
<ul>
	<li><strong>Import Equipment</strong> on the list — <strong>Download Excel Template</strong>, then <strong>Upload &amp; Import</strong>.</li>
	<li><strong>Export LWS-011 PDF</strong> on Monitoring (environmental and equipment contexts).</li>
	<li>Maintenance programmes: <strong>Export Annual Program</strong>, <strong>Export Preventive Program</strong>, <strong>Export Register</strong>, <strong>Export Replacement Plan</strong>.</li>
	<li>Disposal detail may offer a disposal <strong>Report</strong> after execution.</li>
