<h2>What is a pricelist?</h2>
<p>
	A <strong>pricelist</strong> is the price book: agreed selling (and cost) prices for tests or packages,
	usually linked to customers and a currency. When you price a request or build a quote,
	prices come from that book so you are not inventing numbers each time.
</p>

<h2>How they work together</h2>
<ol>
	<li>Keep pricelists up to date (per test or per package) and link the right customers.</li>
	<li>After samples are received (portal or walk-in), open <strong>Process enquiry</strong> to price the work, or build a quote from Billing → Quotations.</li>
	<li>Line totals use unit price × number of samples (or package price × samples).</li>
	<li>Catalogue changes on a pricelist become the live selling price only after <strong>Apply Price Changes</strong>.</li>
</ol>

