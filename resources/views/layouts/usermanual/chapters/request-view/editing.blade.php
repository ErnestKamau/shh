<h2>Editing samples and collection</h2>
<p>
	When the status allows, use <strong>Edit</strong> on sample collection or a sample row
	to fix dates, location, transport, quantities, and related fields. Save from the panel.
	Some fields lock after the request moves further along — follow what is enabled on screen.
</p>

