<h2>The Actions menu</h2>
<p>
	On the receiving board header (and on rows), <strong>Actions</strong> lists what you can do
	for this stage and your role. Typical items include:
</p>
<ul>
	<li>Request more info</li>
	<li>Direct Registration (walk-in intake — see the Direct Registration manual)</li>
	<li>Send Schedule of Analysis</li>
	<li>Receive Samples</li>
	<li>Clone Request</li>
	<li>Reject Request</li>
</ul>

