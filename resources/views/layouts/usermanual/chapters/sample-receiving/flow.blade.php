<h2>Moving a request forward</h2>
<ol>
	<li>Find the request on the receiving board (tab or search).</li>
	<li>Open the row or use Actions → <strong>Receive Samples</strong>.</li>
	<li>Confirm sample type, analysis, condition, specification, and lab.</li>
	<li>Press <strong>Receive Samples</strong> to advance.</li>
	<li>Continue on Integrity &amp; Acceptance, then Accepted, as your process requires.</li>
</ol>

