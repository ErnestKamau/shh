<h3>Visual cues</h3>
<ul>
	<li><strong>Status / tab</strong> — where the request sits.</li>
	<li><strong>Origin badge</strong> — Direct Registration, Walk-in, portal, and similar.</li>
	<li><strong>Row action icons</strong> — view, documents, edit, and next steps.</li>
</ul>

<p>
	For walk-in intake with the Direct Registration button, carousel, and form steps,
	use the <strong>Direct Registration</strong> manual.
</p>

