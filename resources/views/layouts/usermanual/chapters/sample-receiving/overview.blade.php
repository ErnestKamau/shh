<h2>The receiving board</h2>
<p>
	<strong>Samples Receiving</strong> shows requests that need intake attention.
	Summary cards and tabs help you jump between Submitted, Ready for Reception,
	Integrity &amp; Acceptance, Accepted, and related queues.
</p>

