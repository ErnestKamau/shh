<h2>Statuses and what you can do</h2>
<p>
	Receiving usually moves through ideas like: submitted → ready for reception →
	integrity &amp; acceptance → accepted. Only certain actions are offered on each tab.
</p>

<ul>
	<li><strong>Ready for Reception</strong> — receive samples, open the request, start Direct Registration for walk-ins (see the Direct Registration manual).</li>
	<li><strong>Integrity &amp; Acceptance</strong> — confirm condition and accept into lab work.</li>
	<li><strong>Accepted</strong> — jobs created; commercial and lab work continue as your process defines.</li>
</ul>

